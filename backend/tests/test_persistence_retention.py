@pytest.mark.asyncio
async def test_audit_retention_pruning_safely_blocked_to_protect_hash_chain(retention_db):
    """Audit pruning is blocked to prevent breaking the sequential SHA-256 hash chain."""
    session_factory = retention_db["session_factory"]
    retention_svc: RetentionService = retention_db["retention_service"]
    audit_repo: AuditRepository = retention_db["retention_service"].audit_repo

    now = datetime(2026, 10, 20, 12, 0, 0, tzinfo=timezone.utc)
    cutoff = now - timedelta(days=365)

    # Create 3 audit records with valid sequential hash chain
    async with session_factory() as session:
        async with session.begin():
            await audit_repo.log_event(
                session=session,
                actor_id="test",
                action="INVESTIGATION_CREATED",
                resource_type="investigation",
                resource_id="inv-1",
                outcome="SUCCESS",
                request_id="req-1",
                timestamp=cutoff - timedelta(days=5),  # 370 days old
            )
            await audit_repo.log_event(
                session=session,
                actor_id="test",
                action="INVESTIGATION_COMPLETED",
                resource_type="investigation",
                resource_id="inv-1",
                outcome="SUCCESS",
                request_id="req-1",
                timestamp=cutoff - timedelta(days=4),  # 369 days old
            )
            await audit_repo.log_event(
                session=session,
                actor_id="test",
                action="INVESTIGATION_VIEWED",
                resource_type="investigation",
                resource_id="inv-1",
                outcome="SUCCESS",
                request_id="req-2",
                timestamp=now - timedelta(days=1),  # Active
            )

    # Verify chain integrity prior to test
    async with session_factory() as session:
        valid, count, err = await audit_repo.verify_chain_integrity(session)
        assert valid is True
        assert count == 3
        assert err is None

    # Execute audit retention pruning with dry_run=False
    audit_res = await retention_svc.prune_expired_audit_events(dry_run=False, now=now)

    # Must be BLOCKED with 0 deletions to protect hash-chain
    assert audit_res.status == "BLOCKED"
    assert audit_res.deleted_count == 0
    assert audit_res.eligible_count == 2
    assert "ADR-012 sequential SHA-256 hash-chain" in audit_res.reason

    # Verify all 3 audit records survived and chain integrity remains 100% intact
    async with session_factory() as session:
        valid, count, err = await audit_repo.verify_chain_integrity(session)
        assert valid is True
        assert count == 3
        assert err is None


