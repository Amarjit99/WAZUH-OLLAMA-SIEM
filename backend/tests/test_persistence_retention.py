@pytest.mark.asyncio
async def test_dry_run_identifies_candidates_without_modifications(retention_db):
    """Dry-run accurately counts expired investigations and audit events without mutating data."""
    session_factory = retention_db["session_factory"]
    retention_svc: RetentionService = retention_db["retention_service"]

    now = datetime(2026, 10, 20, 12, 0, 0, tzinfo=timezone.utc)
    inv_cutoff = now - timedelta(days=90)
    audit_cutoff = now - timedelta(days=365)

    async with session_factory() as session:
        async with session.begin():
            # Seed 3 expired investigations (95 days old)
            for i in range(1, 4):
                inv = Investigation(
                    investigation_id=f"inv-old-{i}",
                    alert_id=f"alert-old-{i}",
                    run_sequence=1,
                    status="completed",
                    primary_rule_id="5710",
                    created_at=inv_cutoff - timedelta(days=i),
                    updated_at=inv_cutoff - timedelta(days=i),
                )
                session.add(inv)

            # Seed 2 active investigations (45 days old)
            for i in range(1, 3):
                inv = Investigation(
                    investigation_id=f"inv-active-{i}",
                    alert_id=f"alert-active-{i}",
                    run_sequence=1,
                    status="completed",
                    primary_rule_id="5710",
                    created_at=inv_cutoff + timedelta(days=i * 10),
                    updated_at=inv_cutoff + timedelta(days=i * 10),
                )
                session.add(inv)

            # Seed 2 expired audit events (400 days old)
            for i in range(1, 3):
                ev = AuditEvent(
                    audit_id=f"audit-old-{i}",
                    timestamp=audit_cutoff - timedelta(days=i),
                    actor_id="test",
                    action="INVESTIGATION_CREATED",
                    resource_type="investigation",
                    resource_id=f"inv-old-{i}",
                    outcome="SUCCESS",
                    request_id="req-1",
                    client_ip="127.0.0.1",
                    previous_hash="0" * 64,
                    event_hash=f"hash-old-{i}",
                )
                session.add(ev)

            # Seed 3 active audit events (10 days old)
            for i in range(1, 4):
                ev = AuditEvent(
                    audit_id=f"audit-active-{i}",
                    timestamp=now - timedelta(days=i),
                    actor_id="test",
                    action="INVESTIGATION_VIEWED",
                    resource_type="investigation",
                    resource_id=f"inv-active-{i}",
                    outcome="SUCCESS",
                    request_id="req-2",
                    client_ip="127.0.0.1",
                    previous_hash="0" * 64,
                    event_hash=f"hash-active-{i}",
                )
                session.add(ev)

    # 1. Run estimate_cleanup_candidates
    candidates = await retention_svc.estimate_cleanup_candidates(now=now)
    assert candidates.expired_investigations_count == 3
    assert candidates.expired_audit_events_count == 2

    # 2. Run prune_expired_investigations in dry-run mode
    inv_dry = await retention_svc.prune_expired_investigations(dry_run=True, now=now)
    assert inv_dry.dry_run is True
    assert inv_dry.deleted_count == 0
    assert inv_dry.remaining_count == 3
    assert inv_dry.status == "DRY_RUN"

    # 3. Verify zero database rows were deleted or modified
    async with session_factory() as session:
        inv_count = (await session.execute(select(func.count(Investigation.investigation_id)))).scalar_one()
        audit_count = (await session.execute(select(func.count(AuditEvent.audit_id)))).scalar_one()
        assert inv_count == 5
        assert audit_count == 5


@pytest.mark.asyncio
async def test_investigation_boundary_comparison(retention_db):
    """Test boundary condition: created_at < cutoff is purged; created_at == cutoff and > cutoff are preserved."""
    session_factory = retention_db["session_factory"]
    retention_svc: RetentionService = retention_db["retention_service"]

    now = datetime(2026, 10, 20, 12, 0, 0, tzinfo=timezone.utc)
    cutoff = now - timedelta(days=90)  # 2026-07-22 12:00:00

    async with session_factory() as session:
        async with session.begin():
            # 1 second before cutoff -> Expired (< cutoff)
            session.add(Investigation(
                investigation_id="inv-before-cutoff",
                alert_id="alert-1",
                run_sequence=1,
                status="completed",
                primary_rule_id="5710",
                created_at=cutoff - timedelta(seconds=1),
            ))
            # Exactly at cutoff -> Preserved (NOT < cutoff)
            session.add(Investigation(
                investigation_id="inv-at-cutoff",
                alert_id="alert-2",
                run_sequence=1,
                status="completed",
                primary_rule_id="5710",
                created_at=cutoff,
            ))
            # 1 second after cutoff -> Preserved (> cutoff)
            session.add(Investigation(
                investigation_id="inv-after-cutoff",
                alert_id="alert-3",
                run_sequence=1,
                status="completed",
                primary_rule_id="5710",
                created_at=cutoff + timedelta(seconds=1),
            ))

    # Execute destructive pruning
    result = await retention_svc.prune_expired_investigations(dry_run=False, now=now)
    assert result.deleted_count == 1
    assert result.remaining_count == 0

    # Verify which records survived
    async with session_factory() as session:
        survivors = (await session.execute(
            select(Investigation.investigation_id).order_by(Investigation.investigation_id.asc())
        )).scalars().all()
        assert survivors == ["inv-after-cutoff", "inv-at-cutoff"]


@pytest.mark.asyncio
async def test_investigation_retention_cascades_children_and_preserves_audit(retention_db):
    """Deleting expired investigations cascades to child tables but leaves audit events intact."""
    session_factory = retention_db["session_factory"]
    persistence_svc: InvestigationPersistenceService = retention_db["persistence_service"]
    retention_svc: RetentionService = retention_db["retention_service"]

    now = datetime(2026, 10, 20, 12, 0, 0, tzinfo=timezone.utc)
    inv_id = "inv-cascade-test"
    alert = make_sample_alert("alert-casc-01")
    pkg = make_sample_evidence_package(alert)
    res = make_sample_result("alert-casc-01", inv_id)

    # 1. Create completed investigation with all child records via persistence service
    await persistence_svc.start_investigation(inv_id, alert)
    await persistence_svc.complete_investigation(inv_id, res, pkg, duration_ms=250)

    # Manually backdate created_at to 100 days ago
    past_date = now - timedelta(days=100)
    async with session_factory() as session:
        async with session.begin():
            inv = await session.get(Investigation, inv_id)
            inv.created_at = past_date

    # Verify children exist prior to pruning
    async with session_factory() as session:
        assert (await session.execute(select(func.count(InvestigationResultModel.result_id)))).scalar_one() == 1
        assert (await session.execute(select(func.count(InvestigationFact.fact_id)))).scalar_one() == 1
        assert (await session.execute(select(func.count(InvestigationHypothesis.hypothesis_id)))).scalar_one() == 1
        assert (await session.execute(select(func.count(InvestigationCheck.check_id)))).scalar_one() == 1
        assert (await session.execute(select(func.count(InvestigationEvidenceSnapshot.snapshot_id)))).scalar_one() == 1
        audit_count_before = (await session.execute(select(func.count(AuditEvent.audit_id)))).scalar_one()
        assert audit_count_before >= 1  # Persistence service logged INVESTIGATION_COMPLETED

    # 2. Execute destructive investigation pruning
    prune_res = await retention_svc.prune_expired_investigations(dry_run=False, now=now)
    assert prune_res.deleted_count == 1
    assert prune_res.status == "COMPLETED"

    # 3. Verify ALL child records were cascade-deleted
    async with session_factory() as session:
        assert (await session.execute(select(func.count(Investigation.investigation_id)))).scalar_one() == 0
        assert (await session.execute(select(func.count(InvestigationResultModel.result_id)))).scalar_one() == 0
        assert (await session.execute(select(func.count(InvestigationFact.fact_id)))).scalar_one() == 0
        assert (await session.execute(select(func.count(InvestigationHypothesis.hypothesis_id)))).scalar_one() == 0
        assert (await session.execute(select(func.count(InvestigationCheck.check_id)))).scalar_one() == 0
        assert (await session.execute(select(func.count(InvestigationEvidenceSnapshot.snapshot_id)))).scalar_one() == 0

        # 4. Verify audit_events survived AND a new INVESTIGATION_EXPIRED_PRUNED event was recorded
        audit_events = (await session.execute(
            select(AuditEvent).order_by(AuditEvent.timestamp.asc())
        )).scalars().all()
        assert len(audit_events) == audit_count_before + 1
        prune_event = audit_events[-1]
        assert prune_event.action == "INVESTIGATION_EXPIRED_PRUNED"
        assert prune_event.outcome == "SUCCESS"


